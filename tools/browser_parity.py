"""
tools/browser_parity.py - SGT and SDIS reads of the same fictional pages in every browser (Part R.2)
===================================================================================================
Serves fictional pages on 127.0.0.1 (the two tests/class_diff_align clients, regenerated by
make_clients.py, and make_form.py's form with a dropdown, radio buttons, a checkbox and a password
box), opens each installed browser (Chrome, Edge, Firefox) ALONE with a throwaway profile, reads
each page the way SGT and SDIS do, closes only the processes it started, deletes the profile and
prints a parity table: address read, SGT lines (plus "Selected:" lines and the lines that differ
between browsers), whether the fictional password was ever read (must be NO), node counts, ms.

Client A is opened with client B as a second tab: SGT's lines must hold A's values only (a page
in a background tab is never read).

The reads of the two clients are saved as fixtures, tests/class_diff_align/client_{A,B}_<browser>.json,
in key_probe --once format with every 127.0.0.1 address replaced by test.local.

Never touches any window or process it did not start: windows are looked for only among the
started browser's own processes, and closing terminates that process tree by PID, never by name.
Opening the browsers takes focus for about half a minute per browser.

Usage:
    python tools/browser_parity.py                        # every installed browser
    python tools/browser_parity.py --browsers firefox     # only some (chrome, msedge, firefox)
    python tools/browser_parity.py --md docs/sdis/firefox-parity.md --no-fixtures
"""

